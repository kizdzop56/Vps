// ─────────────────────────────────────────────────────────────────────────────
// Раздел «Составлять»: журнал ответов.
//
// Одна строка — один ответ ученика. Журнал нужен для четырёх вещей:
//   1. дневной потолок очков (сколько уже начислено сегодня);
//   2. статистика «что даётся хуже всего» — по временам и по глаголам;
//   3. знакомость глагола: сколько верных ответов по нему уже есть. От этого
//      зависит, спрашивать форму вариантами или письмом;
//   4. история: без неё нельзя ответить даже на вопрос «он вообще занимался?».
//
// ── Почему очки хранятся, а не пересчитываются ──────────────────────────────
// В словах сделано наоборот: там «начислено за сегодня» считается по журналу
// текущими правилами. Это уже стоило отдельной правки — правила начисления
// поменялись, а старые записи остались, и потолок стал считаться по новым
// ставкам для ответов, данных при старых. Здесь начисленное записано в строку:
// сколько выдали, столько и учитываем.
//
// ── topic ───────────────────────────────────────────────────────────────────
// Что именно тренировалось: id времени («past_simple») или первая форма глагола
// («go»). Отдельная колонка, а не разбор taskId строкой: по ней собирается
// статистика, а формат номеров заданий — внутреннее дело банка и меняться может
// свободно.
// ─────────────────────────────────────────────────────────────────────────────
import { pgTable, serial, integer, text, boolean, timestamp, index } from "drizzle-orm/pg-core";
import { usersTable } from "./users";

export const grammarLogTable = pgTable("grammar_log", {
  id: serial("id").primaryKey(),
  userId: integer("user_id").notNull().references(() => usersTable.id, { onDelete: "cascade" }),
  /**
   * Номер задания. У банков это строка из tasks.ts, у форм глагола —
   * вычисляемый номер вида «vf:past:buy». Не ссылка: заданий в БД нет вовсе.
   */
  taskId: text("task_id").notNull(),
  /** forms | verbs | tense | build */
  mode: text("mode").notNull(),
  /**
   * Время («past_simple») или глагол («go»). Для сборки предложений пусто.
   *
   * У режима форм это первая форма глагола — та же тема, что и у заданий с
   * предложениями, поэтому статистика по глаголу собирается из обоих режимов.
   */
  topic: text("topic"),
  /** Как отвечали: type | choice | assemble. Письмо труднее выбора — и дороже. */
  input: text("input").notNull(),
  correct: boolean("correct").notNull(),
  /** Принято с опечаткой: ответ верный, но написание показали. */
  typo: boolean("typo").notNull().default(false),
  /** Сколько очков реально начислено — с учётом дневного потолка. */
  pointsEarned: integer("points_earned").notNull().default(0),
  answeredAt: timestamp("answered_at").notNull().defaultNow(),
}, (t) => [
  // Оба запроса раздела ходят по одному и тому же: ответы ОДНОГО ученика за
  // период. Без индекса это полный проход по таблице на каждый ответ.
  index("grammar_log_user_time_idx").on(t.userId, t.answeredAt),
]);

export type GrammarLog = typeof grammarLogTable.$inferSelect;
