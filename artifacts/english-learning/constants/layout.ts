// ─────────────────────────────────────────────────────────────────────────────
// Отступы экрана от системных краёв.
//
// Почему это вынесено в отдельный файл: раньше каждый экран писал
//
//   paddingTop: insets.top + (Platform.OS === "web" ? 67 : 16)
//
// Цифра 67 появилась во времена превью в редакторе, где сверху висела
// собственная панель браузера, и с тех пор разъехалась по двадцати экранам.
// На боевом домене этой панели нет: safe-area-context в мобильном браузере
// уже возвращает высоту чёлки и статус-бара, поэтому 67 пикселей сверх неё —
// просто пустая полоса. На айфоне это съедало примерно восьмую часть экрана
// до того, как начинался контент.
//
// Теперь величина одна и лежит здесь. Если когда-нибудь понадобится отступ
// под внешнюю панель, он правится в одном месте, а не поиском по проекту.
// ─────────────────────────────────────────────────────────────────────────────

import type { EdgeInsets } from "react-native-safe-area-context";

/** Воздух между системной областью и первым элементом экрана. */
export const SCREEN_TOP_GAP = 12;

/**
 * Верхний отступ содержимого экрана.
 *
 * @param insets значение useSafeAreaInsets()
 * @param extra  дополнительный воздух для экранов, где заголовок крупнее
 */
export function screenTop(insets: Pick<EdgeInsets, "top">, extra = 0): number {
  // Минимум на случай, если браузер не отдал safe-area (десктоп, старый WebView):
  // без него заголовок прилипал бы к самому верху окна.
  return Math.max(insets.top, 10) + SCREEN_TOP_GAP + extra;
}

// ─────────────────────────────────────────────────────────────────────────────
// Нижняя панель вкладок ПЛАВАЮЩАЯ: она лежит поверх содержимого
// (position: absolute в app/(main)/_layout.tsx), а не занимает место в потоке.
// Значит, прокрутка о ней ничего не знает, и последний блок экрана уезжает
// под панель — так пропадала нижняя половина витрины наград в чужом профиле:
// список кончался, докрутить было некуда, а медали оставались за панелью.
//
// Отсюда правило: у КАЖДОГО экрана со своей прокруткой contentContainerStyle
// должен получать screenBottom(insets). Иначе край экрана всегда будет
// съеден на высоту панели.
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Высота самой панели: 9 сверху + 38 иконка + 3 зазор + 13 подпись + 9 снизу.
 * Совпадает с вёрсткой CustomTabBar — при её правке меняется и это число.
 */
export const TAB_BAR_HEIGHT = 72;

/** Насколько панель приподнята над системной областью. */
export const TAB_BAR_LIFT = 8;

/** Воздух между последним блоком и панелью: без него блок липнет к ней. */
export const SCREEN_BOTTOM_GAP = 20;

/**
 * Нижний отступ содержимого для экранов с плавающей панелью вкладок.
 *
 * @param insets значение useSafeAreaInsets()
 * @param extra  дополнительный воздух (например, под липкую кнопку экрана)
 */
export function screenBottom(insets: Pick<EdgeInsets, "bottom">, extra = 0): number {
  // Math.max повторяет расчёт панели: на устройствах без домашней полосы
  // insets.bottom равен нулю, а панель всё равно отступает от края.
  return Math.max(insets.bottom, 8) + TAB_BAR_LIFT + TAB_BAR_HEIGHT + SCREEN_BOTTOM_GAP + extra;
}

export default screenTop;
