// ─────────────────────────────────────────────────────────────────────────────
// Отступы экрана от системных краёв.
//
// Почему это вынесено в отдельный файл: раньше каждый экран писал
//
//   paddingTop: insets.top + (Platform.OS === "web" ? 67 : 16)
//
// Цифра 67 появилась во времена превью в редакторе, где сверху висела
// собственная панель браузера, и с тех пор разъехалась по двадцати экранам.
// На боевом домене этой панели нет: safe-area-context в мобильном браузере
// уже возвращает высоту чёлки и статус-бара, поэтому 67 пикселей сверх неё —
// просто пустая полоса. На айфоне это съедало примерно восьмую часть экрана
// до того, как начинался контент.
//
// Теперь величина одна и лежит здесь. Если когда-нибудь понадобится отступ
// под внешнюю панель, он правится в одном месте, а не поиском по проекту.
// ─────────────────────────────────────────────────────────────────────────────

import type { EdgeInsets } from "react-native-safe-area-context";

/** Воздух между системной областью и первым элементом экрана. */
export const SCREEN_TOP_GAP = 12;

/**
 * Верхний отступ содержимого экрана.
 *
 * @param insets значение useSafeAreaInsets()
 * @param extra  дополнительный воздух для экранов, где заголовок крупнее
 */
export function screenTop(insets: Pick<EdgeInsets, "top">, extra = 0): number {
  // Минимум на случай, если браузер не отдал safe-area (десктоп, старый WebView):
  // без него заголовок прилипал бы к самому верху окна.
  return Math.max(insets.top, 10) + SCREEN_TOP_GAP + extra;
}

export default screenTop;
