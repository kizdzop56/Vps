// ─────────────────────────────────────────────────────────────────────────────
// СНЕЖА ИЗ ГОТОВЫХ КАДРОВ: стоит статично, говорит покадрово.
//
// ── Почему картинки, а не вектор ────────────────────────────────────────────
// До этого Снежа была нарисована путями (components/SnezhaLive.tsx). Рисунок
// оживал как надо, но это была ДРУГАЯ Снежа: свои пропорции, свой взгляд, своя
// линия. Рядом с настоящей картинкой из приложения разница видна сразу.
//
// Теперь кадры — те самые файлы, что нарисованы для персонажа.
//
// ── ПОЧЕМУ ИМЕНА ФАЙЛОВ ТАКИЕ СТРАННЫЕ ─────────────────────────────────────
// IMG_7928…IMG_7937 — это имена прямо из фотогалереи телефона. Кадры заливал
// человек с телефона, и переименовать десять файлов в мобильном интерфейсе
// GitHub заметно труднее, чем кажется.
//
// Осмысленных имён здесь нет намеренно: любое переименование задним числом
// сломало бы ссылки, а пользы дало бы ноль — порядок всё равно задан массивом
// ниже, а не именами.
//
// ── ПОЛЯ И ФОН СРЕЗАЮТСЯ ЗДЕСЬ ─────────────────────────────────────────────
// Файлы залиты КАК ЕСТЬ: белый фон и широкие пустые поля вокруг зверя (силуэт
// занимает 57 % ширины и 88 % высоты картинки). Показать такой файл целиком —
// значит отдать половину места пустоте и получить крошечную Снежу.
//
// Поэтому рамка обрезает поля: контейнер с overflow: hidden, а картинка внутри
// больше него и сдвинута так, чтобы в окно попал ровно силуэт. Границы
// измерены по самим файлам (CROP ниже) — и они ОБЩИЕ для всех кадров.
//
// Общие, а не по каждому кадру, именно чтобы Снежа не дёргалась: у распахнутого
// рта силуэт ниже, чем у закрытого, и обрезка «по месту» заставила бы зверя
// подпрыгивать на каждом кадре речи.
//
// Белый фон не вырезан (в файлах он есть), поэтому он оформлен как белая
// карточка со скруглением и тонкой рамкой. Так он читается замыслом, а не
// забытым артефактом.
//
// ── ГРАБЛИ: КАДРЫ НЕЛЬЗЯ ПОДСТАВЛЯТЬ ПО ОДНОМУ ─────────────────────────────
// Очевидное решение — рисовать один <Image> и менять ему source. Так делать
// нельзя: каждый новый файл начинает грузиться в момент показа, и первый круг
// речи идёт с дырками — кадр то есть, то белое место. На вебе особенно заметно,
// там картинки тянутся по сети.
//
// Поэтому ВСЕ кадры лежат в дереве сразу, друг на друге, и переключаются
// ПРОЗРАЧНОСТЬЮ. К моменту первой реплики они уже загружены, и смена кадра
// стоит ноль.
//
// ── Речь ───────────────────────────────────────────────────────────────────
// Кадр держится 110 мс, то есть около девяти кадров в секунду. Столько же
// держит рисованная мультипликация «на двойках», и глазу этого достаточно.
//
// Главное в последовательности — ЗАКРЫТЫЕ кадры. Рот, который открывается и
// закрывается ровным маятником, читается как жующая рыба. Речь состоит из слов,
// между словами губы смыкаются, поэтому в SPEAK регулярно возвращается кадр
// покоя.
//
// Точной синхронизации с голосом тут быть не может: расшифровки своей реплики у
// клиента нет, звук приходит готовым файлом. Но глаз читает совпадение по
// РИТМУ, а не по буквам.
// ─────────────────────────────────────────────────────────────────────────────
import React from "react";
import { View, type StyleProp, type ViewStyle } from "react-native";
import { Image } from "expo-image";

/** Что Снежа делает прямо сейчас. */
export type SnezhaState = "idle" | "listen" | "speak" | "think";

/**
 * Кадр покоя: рот закрыт. Висит на экране всё время, пока Снежа молчит.
 *
 * Отдельной константой, а не «первым элементом массива», чтобы поменять его
 * можно было одной строкой: какой именно файл оказался закрытым, видно только
 * глазами.
 */
const IDLE = require("../assets/images/snezha/IMG_7933.png");

/**
 * Кадры речи. Порядок — тот, в котором они лежат в папке.
 *
 * Раскрытие рта у них разное и вразнобой, и это ХОРОШО: ровная последовательность
 * «шире-шире-уже» как раз и даёт эффект жующей рыбы, а неровная читается живой
 * речью.
 */
const TALK = [
  require("../assets/images/snezha/IMG_7928.png"),
  require("../assets/images/snezha/IMG_7929.png"),
  require("../assets/images/snezha/IMG_7930.png"),
  require("../assets/images/snezha/IMG_7931.png"),
  require("../assets/images/snezha/IMG_7932.png"),
  require("../assets/images/snezha/IMG_7934.png"),
  require("../assets/images/snezha/IMG_7935.png"),
  require("../assets/images/snezha/IMG_7936.png"),
  require("../assets/images/snezha/IMG_7937.png"),
];

/** Все кадры вместе: кадр покоя первым, дальше речь. */
const FRAMES = [IDLE, ...TALK];

/**
 * Что показывать по кругу, пока Снежа говорит.
 *
 * Ноль — кадр покоя, то есть сомкнутые губы. Он возвращается регулярно: без
 * этого рот не закрывается вовсе, и получается не речь, а зевота.
 */
const SPEAK = [1, 4, 2, 0, 6, 3, 8, 0, 5, 7, 2, 0, 9, 4, 6, 0];

/** Сколько держится один кадр речи. */
const TICK_MS = 110;

/**
 * Где на картинке сам зверь. Доли от размера файла, измерены по всем кадрам
 * сразу: слева, сверху, ширина, высота.
 *
 * Менять только если заменили сами файлы. Числа не «на глаз»: по ним считается
 * и размер окна, и сдвиг картинки внутри.
 */
const CROP = { x: 0.2348, y: 0.0646, w: 0.5735, h: 0.8767 };

/** Пропорция ОБРЕЗАННОГО кадра: ширина к высоте. Нужна экранам для расчёта. */
export const SNEZHA_ASPECT = 757 / 1045;

interface Props {
  state?: SnezhaState;
  width?: number;
  /** Остановить кадры: экран не виден или движение сейчас лишнее. */
  still?: boolean;
  style?: StyleProp<ViewStyle>;
}

export function SnezhaFrames({ state = "idle", width = 112, still = false, style }: Props) {
  const height = Math.round(width / SNEZHA_ASPECT);
  const talking = state === "speak" && !still;

  // Картинка больше окна: в окно попадает только силуэт, поля уходят за край.
  const imgW = Math.round(width / CROP.w);
  const imgH = Math.round(height / CROP.h);
  const offsetX = -Math.round(imgW * CROP.x);
  const offsetY = -Math.round(imgH * CROP.y);

  const [step, setStep] = React.useState(0);

  React.useEffect(() => {
    if (!talking) {
      // Замолчала — рот обязан вернуться в закрытое положение, а не застыть на
      // случайном кадре с распахнутой пастью.
      setStep(0);
      return;
    }
    const id = setInterval(() => setStep((s) => (s + 1) % SPEAK.length), TICK_MS);
    return () => clearInterval(id);
  }, [talking]);

  const active = talking ? SPEAK[step % SPEAK.length]! : 0;

  return (
    <View
      pointerEvents="none"
      style={[
        {
          width,
          height,
          // Белый фон в файлах есть, и прятать его нечем — значит он должен
          // выглядеть решением: карточка со скруглением и тонкой рамкой.
          backgroundColor: "#ffffff",
          borderRadius: 18,
          borderWidth: 1,
          borderColor: "rgba(139,92,246,0.22)",
          // Ради этой строки всё и затевалось: поля картинки уходят за край.
          overflow: "hidden",
        },
        style,
      ]}
    >
      {FRAMES.map((src, i) => (
        <Image
          key={i}
          source={src}
          // Все кадры друг на друге: показанный — тот, у которого прозрачность
          // единица. См. ГРАБЛИ в шапке файла.
          style={{
            position: "absolute",
            left: offsetX,
            top: offsetY,
            width: imgW,
            height: imgH,
            opacity: i === active ? 1 : 0,
          }}
          // Именно fill: размеры уже посчитаны, и contain внутри них добавил бы
          // свои поля поверх наших.
          contentFit="fill"
          // Кеш на диске, а не только в памяти: иначе каждое открытие экрана
          // тянет десять файлов заново.
          cachePolicy="memory-disk"
          // Проявления нет намеренно: expo-image анимирует прозрачность по
          // событию загрузки, а мы прозрачностью и переключаем кадры — вместе
          // это даёт мигание.
          transition={0}
          priority={i === 0 ? "high" : "normal"}
        />
      ))}
    </View>
  );
}

export default SnezhaFrames;
