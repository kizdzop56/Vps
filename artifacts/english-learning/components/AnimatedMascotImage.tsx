// ─────────────────────────────────────────────────────────────────────────────
// Картинка маскота.
//
// ── ОДНА КАРТИНКА НА ВСЕ ПОЗЫ ────────────────────────────────────────────────
// Поз было десять, каждая — отдельный файл, вырезанный из своего джипега. Это
// десять шансов на кривую вырезку фона, и два уже выстрелили: у празднующей позы
// на месте ЖИВОТА и внутренности РТА оказались дырки. Через них просвечивал
// экран, и это читалось как «маскот не прорисовался».
//
// Дырки берутся не из кода: фон вырезали по цвету, а живот и рот — такие же
// светлые замкнутые области, как и фон, вот их и вырезало заодно. Никакой размер
// и никакой кеш этого не чинят — дырка просто растёт вместе с картинкой.
//
// Поэтому источник теперь ОДИН файл на всё приложение. Его вырезали заливкой от
// краёв: замкнутые области внутри силуэта остаются на месте по построению.
// Проверить одну картинку можно один раз и навсегда; десять — нельзя.
//
// Тип MascotPose и POSE_RATIO оставлены: по позам расставлены вызовы во всём
// приложении, и менять их ради этой правки незачем. Поза сейчас ни на что не
// влияет — если появится вторая выверенная картинка, SRC станет словарём снова.
//
// ── Пропорция берётся от файла ───────────────────────────────────────────────
// Раньше здесь стояло 9/16 для всех поз, а файлы были другой формы. contentFit
// = contain честно вписывал картинку и добивал разницу пустыми полями: место
// занято, зверь мельче, чем мог бы. Теперь пропорция одна и равна настоящей.
//
// ── Кеш на диске, а не в памяти ──────────────────────────────────────────────
// С cachePolicy="memory" кеш живёт только до перезагрузки страницы, и на
// медленной сети каждое открытие окна тянуло картинку заново.
//
// ── Почему нет анимации проявления ──────────────────────────────────────────
// Была: transition={180}. expo-image на вебе рисует картинку с opacity 0 и
// анимирует её к единице ПО СОБЫТИЮ ЗАГРУЗКИ. Если событие не пришло — а на iOS
// Safari картинка из кэша декодируется синхронно, и событие теряется, — картинка
// остаётся прозрачной: файл загружен, место занято, зверя нет.
//
// ── Ожидание видно ──────────────────────────────────────────────────────────
// Пока картинка идёт по сети, на её месте мягкая плашка с индикатором. Пустота
// на этом месте неотличима от поломки, а на 3G она держится секунды.
// ─────────────────────────────────────────────────────────────────────────────
import React from "react";
import { ActivityIndicator, View } from "react-native";
import { Image } from "expo-image";

export type MascotPose =
  | "wave" | "celebrate" | "think" | "happy" | "excited"
  | "curious" | "point" | "laugh" | "sit" | "lie";

/**
 * Единственная картинка маскота.
 *
 * Заменять файл можно только вырезкой ЗАЛИВКОЙ ОТ КРАЁВ (magic wand по цвету
 * прогрызает живот и рот). После замены обязательно посмотреть картинку на
 * тёмном фоне: на белом дырка не видна вовсе.
 */
const MASCOT = require("../assets/images/mascot_full.png");

/** Настоящая пропорция файла: ширина, делённая на высоту. */
export const MASCOT_ASPECT = 616 / 844;

/**
 * Пропорция позы. Одна на все позы, пока картинка одна.
 *
 * Словарь оставлен, потому что окна считают по нему размер (Mascot, TabGuide,
 * WavingMascot), и второй список пропорций рядом с этим рано или поздно
 * разошёлся бы с первым.
 */
export const POSE_RATIO: Record<MascotPose, number> = {
  wave: MASCOT_ASPECT, celebrate: MASCOT_ASPECT, think: MASCOT_ASPECT,
  happy: MASCOT_ASPECT, excited: MASCOT_ASPECT, curious: MASCOT_ASPECT,
  point: MASCOT_ASPECT, laugh: MASCOT_ASPECT, sit: MASCOT_ASPECT,
  lie: MASCOT_ASPECT,
};

/**
 * Через сколько снимать плашку ожидания, даже если событие загрузки не пришло.
 *
 * Страховка от той же беды, что и с transition: событие может потеряться, а
 * спиннер под уже нарисованным зверем — это хуже, чем отсутствие спиннера.
 */
const WAIT_GIVE_UP_MS = 5000;

interface Props {
  pose?:   MascotPose;
  width?:  number;
  height?: number;
  style?:  any;
}

export function AnimatedMascotImage({ pose = "wave", width = 200, height, style }: Props) {
  const imgW = width;
  const imgH = height ?? Math.round(width / POSE_RATIO[pose]);

  const [waiting, setWaiting] = React.useState(true);
  /** Одна повторная попытка: на мобильной сети запрос отваливается сам по себе. */
  const [attempt, setAttempt] = React.useState(0);

  React.useEffect(() => {
    if (!waiting) return;
    const t = setTimeout(() => setWaiting(false), WAIT_GIVE_UP_MS);
    return () => clearTimeout(t);
  }, [waiting, attempt]);

  return (
    <View style={[{ width: imgW, height: imgH }, style]}>
      {waiting && (
        <View
          pointerEvents="none"
          style={{
            position: "absolute", left: 0, right: 0, top: 0, bottom: 0,
            borderRadius: 28,
            backgroundColor: "rgba(168,85,247,0.10)",
            alignItems: "center", justifyContent: "center",
          }}
        >
          <ActivityIndicator color="#c084fc" />
        </View>
      )}
      <Image
        // Ключ меняется при повторной попытке: без этого expo-image считает
        // источник тем же самым и заново не запрашивает.
        key={`mascot-${attempt}`}
        source={MASCOT}
        style={{ width: imgW, height: imgH }}
        contentFit="contain"
        cachePolicy="memory-disk"
        priority="high"
        // onLoadEnd, а не onLoad: срабатывает и на успехе, и на ошибке, поэтому
        // плашка не залипает на неудачной загрузке.
        onLoadEnd={() => setWaiting(false)}
        onError={() => setAttempt((a) => (a === 0 ? 1 : a))}
      />
    </View>
  );
}
