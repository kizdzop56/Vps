// ─────────────────────────────────────────────────────────────────────────────
// Монета рейда.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Монеты показывались глифом «cup» — кубком, который на
// маленьком размере читается как кружка с ручкой. Для валюты это просто
// неверный знак: ученик видит стакан там, где написано «монеты».
//
// В общий набор (components/ui/Glyph.tsx) монета не поехала осознанно: там
// ВСЕ значки нарисованы контуром одной толщины и перекрашиваются одним цветом,
// а монета обязана быть заливной и двухцветной — иначе она не читается как
// монета, а выглядит кружком. Смешивать в одном наборе два языка форм хуже, чем
// держать одно исключение рядом с местом, где оно нужно.
//
// Если монеты выйдут за пределы рейда (например, в общий магазин), знак стоит
// перевести в Glyph и привести к его правилам.
// ─────────────────────────────────────────────────────────────────────────────
import React from "react";
import Svg, { Circle, Path, Defs, LinearGradient, Stop } from "react-native-svg";

export interface CoinProps {
  size?: number;
  /** Основной цвет. По умолчанию золото палитры. */
  color?: string;
  /** Тень/ободок: тёмная версия основного цвета. */
  edge?: string;
}

/**
 * Монета: круг с ободком и звездой внутри.
 *
 * Звезда, а не цифра и не знак валюты: цифру пришлось бы переводить, а знак
 * валюты привязал бы игровые монеты к деньгам, которых в приложении нет.
 */
export function Coin({ size = 20, color = "#fbbf24", edge = "#b45309" }: CoinProps) {
  const id = React.useId();
  return (
    <Svg width={size} height={size} viewBox="0 0 24 24">
      <Defs>
        <LinearGradient id={id} x1="0" y1="0" x2="1" y2="1">
          <Stop offset="0" stopColor={color} />
          <Stop offset="1" stopColor={edge} />
        </LinearGradient>
      </Defs>
      {/* Корпус и ободок: без ободка монета сливается со светлым фоном карточки. */}
      <Circle cx={12} cy={12} r={9.4} fill={`url(#${id})`} />
      <Circle cx={12} cy={12} r={9.4} stroke={edge} strokeWidth={1.6} fill="none" />
      <Circle cx={12} cy={12} r={6.6} stroke={edge} strokeWidth={1.1} fill="none" opacity={0.55} />
      {/* Звезда: заливка светлее корпуса, поэтому видна и на 16 пикселях. */}
      <Path
        d="m12 7.4 1.42 2.98 3.18.42-2.35 2.2.6 3.2L12 14.65 9.15 16.2l.6-3.2-2.35-2.2 3.18-.42L12 7.4Z"
        fill="#fff7e0"
      />
    </Svg>
  );
}

export default Coin;
