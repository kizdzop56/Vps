// ─────────────────────────────────────────────────────────────────────────────
// Версии юридических документов.
//
// Зачем версия, а не просто флаг «согласился». Согласие даётся не «вообще», а на
// КОНКРЕТНУЮ редакцию текста. Как только в политике появляется новый способ
// обработки данных (например, подключили аналитику), прежнее согласие его не
// покрывает. Без версии отличить «согласился с текущей редакцией» от «согласился
// со старой два года назад» невозможно, и пришлось бы переспрашивать всех.
//
// Формат — дата редакции. Строкой, а не числом: сравнивать версии как больше/меньше
// не нужно, нужно только равенство текущей.
//
// ПОДНЯЛ ВЕРСИЮ — значит все старые согласия стали устаревшими, и клиент снова
// покажет экран согласия. Не поднимай ради опечаток.
// ─────────────────────────────────────────────────────────────────────────────

/** Текущая редакция пользовательского соглашения. */
export const TERMS_VERSION = "2026-08-20";

/** Текущая редакция политики конфиденциальности. */
export const PRIVACY_VERSION = "2026-08-20";

/** Кто дал согласие. У ребёнка своё согласие юридической силы не имеет. */
export type ConsentBy = "self" | "parent" | "teacher";

export const CONSENT_BY: readonly ConsentBy[] = ["self", "parent", "teacher"];

export function isConsentBy(value: unknown): value is ConsentBy {
  return typeof value === "string" && (CONSENT_BY as readonly string[]).includes(value);
}

/**
 * С какого возраста согласие человека действительно само по себе.
 *
 * GDPR ст. 8 даёт странам вилку 13–16 лет; берём строгий край, потому что он
 * подходит везде, а мягкий — не везде.
 */
export const SELF_CONSENT_AGE = 16;

/** Нужен ли родительский путь согласия. Возраст неизвестен — считаем, что нужен. */
export function needsParentConsent(role: string, age: number | null): boolean {
  if (role !== "student") return false;
  if (age === null || !Number.isFinite(age)) return true;
  return age < SELF_CONSENT_AGE;
}
