// ─────────────────────────────────────────────────────────────────────────────
// Код регистрации учителя.
//
// ── Почему он больше не в коде ──────────────────────────────────────────────
// Раньше в routes/auth.ts лежала строка `const TEACHER_CODE = "422668"`, и та же
// строка была продублирована в клиентском экране регистрации, то есть уезжала в
// собранный веб-бандл. Репозиторий открытый: кто угодно читал код, регистрировал
// себе учителя и получал доступ к спискам учеников, их работам и разборам.
//
// Теперь код живёт ТОЛЬКО в переменной окружения TEACHER_CODE на сервере.
// Клиент про него не знает ничего: он отправляет введённое значение и получает
// ответ. Сменить код = поменять переменную и перезапустить сервис, без правок
// кода и без нового деплоя фронтенда.
//
// ── Переменной нет — учителей не создать ────────────────────────────────────
// Регистрация учителя в этом случае отвечает 503, а не пускает всех подряд. Роль
// учителя видит чужие персональные данные, поэтому поведение по умолчанию должно
// быть «нельзя».
//
// ── Сравнение не по === ─────────────────────────────────────────────────────
// Обычное сравнение строк выходит на первом различающемся символе, и по времени
// ответа код подбирается посимвольно. Поэтому сравниваем свёртки постоянного
// размера через timingSafeEqual.
// ─────────────────────────────────────────────────────────────────────────────
import crypto from "node:crypto";

/** Короче этого код бессмысленен: перебирается за минуты. */
const MIN_CODE_LEN = 4;

const CONFIGURED = process.env["TEACHER_CODE"]?.trim() ?? "";

/** Можно ли вообще регистрировать учителей на этом сервере. */
export function teacherSignupEnabled(): boolean {
  return CONFIGURED.length >= MIN_CODE_LEN;
}

function digest(value: string): Buffer {
  return crypto.createHash("sha256").update(value, "utf8").digest();
}

/** Совпадает ли присланный код с настроенным. */
export function teacherCodeMatches(given: unknown): boolean {
  if (!teacherSignupEnabled()) return false;
  if (typeof given !== "string") return false;
  const candidate = given.trim();
  if (candidate.length === 0) return false;
  // Свёртки одинаковой длины: timingSafeEqual требует равных буферов и сам не
  // выдаёт разницу по времени.
  return crypto.timingSafeEqual(digest(candidate), digest(CONFIGURED));
}
