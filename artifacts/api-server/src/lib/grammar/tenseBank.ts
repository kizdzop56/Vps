// Банк заданий на времена целиком: написанное руками плюс сгенерированное.
//
// Почему отдельным файлом. В tenseTasks.ts лежат двести с лишним заданий,
// написанных вручную, и лезть в этот файл ради одной строки склейки незачем:
// чем реже его открываешь, тем меньше шансов случайно испортить данные.
//
// Порядок: ручное впереди. Оно вычитано, и если банк уровня вдруг окажется
// меньше одного захода, ученик увидит именно его.
//
// Сгенерированное берётся из предложений-заготовок (см. sentenceUnits.ts и
// generate.ts) в два шага:
//
//   1. одна заготовка даёт утверждение, отрицание и два вида вопроса — так банк
//      вырос с 216 заданий примерно до семисот;
//   2. заготовка с меткой swap разворачивается по шести лицам, и семьсот
//      превращаются в несколько тысяч. Русские формы для этого лежат в
//      ruForms.ts, английские считает та же механика, что и раньше.
//
// Ни одного придуманного машиной предложения при этом не появляется: смысл
// написан руками, меняются лицо и грамматическая форма.
// ─────────────────────────────────────────────────────────────────────────────

