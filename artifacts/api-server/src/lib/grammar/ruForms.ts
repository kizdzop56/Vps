/**
 * Подлежащее для подстановки.
 *
 * Только местоимения. Существительные («The shop», «My father») не
 * подставляются: у русского слова свой род, и в прошедшем времени пришлось бы
 * знать его для каждого — а главное, смысл фразы обычно завязан именно на этом
 * подлежащем. Местоимений шести штук хватает, чтобы вырастить банк в разы.
 */
export type SwapSubject = {
  /** Уходит в номер задания: g-u-ps-1-they-aff. */
  key: string;
  en: string;
  ru: string;
  person: Person;
  /** Позиция в present и future. */
  personIndex: 0 | 1 | 2 | 3 | 4;
  /** Позиция в past: род и число. */
  pastIndex: 0 | 1 | 2 | 3;
  /** Притяжательное местоимение — подставляется на место {poss} в хвосте. */
  poss: string;
};

