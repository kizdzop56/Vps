/**
 * Притяжательное местоимение по лицу.
 *
 * Нужно и для РОДНОГО подлежащего заготовки, которое местоимением быть не
 * обязано: у «My mother» лицо she, значит {poss} — her.
 */
export const POSSESSIVE: Record<Person, string> = {
  I: "my",
  you: "your",
  he: "his",
  she: "her",
  it: "its",
  we: "our",
  they: "their",
};

/** Форма глагола для этого лица и русского времени. null — формы нет в таблице. */
export function ruVerbForm(key: string, tense: RuTense, subject: SwapSubject): string | null {
  const forms = RU_VERBS[key];
  if (!forms) return null;

  if (tense === "past") {
    return forms.past?.[subject.pastIndex] ?? null;
  }
  const row = tense === "future" ? forms.future : forms.present;
  return row?.[subject.personIndex] ?? null;
}
