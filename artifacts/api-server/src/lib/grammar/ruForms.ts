// ─────────────────────────────────────────────────────────────────────────────
// Русские формы глаголов и подлежащие для размножения заготовок.
//
// ── Зачем ───────────────────────────────────────────────────────────────────
// Заготовка предложения (sentenceUnits.ts) написана под ОДНО лицо: «He goes to
// bed at ten». Английская механика из неё выводится вся — утверждение,
// отрицание, вопрос, — но только для этого лица, потому что русский перевод
// хранится готовой строкой: «Он ложится спать в десять».
//
// Отсюда и упирался объём раздела: 120 заготовок дают около 700 заданий на
// времена и 360 на сборку, то есть 58 и 30 заходов. При пяти заходах в день это
// две недели, и дальше пойдёт второй круг.
//
// Английскую часть размножить по лицам легко: «I go», «She goes», «They go» —
// это ровно та механика, которую генератор и так считает. Мешает русский: у
// глагола меняется форма («хожу», «ходит», «ходят»), а в прошедшем ещё и род
// («ходил», «ходила»). Поэтому здесь лежит таблица форм, а заготовка ссылается
// на неё ключом.
//
// ── Почему таблица, а не правила ────────────────────────────────────────────
// Самодельной русской морфологии в этом проекте уже хватило: в разделе слов она
// сравнивала переводы по обрезанной основе и предлагала стереть нормальные
// карточки (см. WORDS.md). Русское спряжение правилами не берётся — «пить» даёт
// «пью», «идти» даёт «шёл». Поэтому формы написаны руками, а тест сверяет их с
// тем, что уже стоит в заготовке: расхождение в таблице падает на сборке, а не
// у ученика на экране.
//
// ── Порядок форм ────────────────────────────────────────────────────────────
// present и future: я | ты | он, она, оно | мы | они
// past:             он | она | оно | они
//
// «Вы» как вежливое обращение не заводим: английское you переводим как «ты» —
// приложение для детей, и учитель обращается к ученику именно так.
//
// В прошедшем времени у «я» и «ты» берётся мужская форма. Это условность, но
// принятая: так же поступают учебники, а спрашивать пол ученика ради одной
// буквы в переводе — цена выше пользы.
//
// ── Заполнено то, что нужно ─────────────────────────────────────────────────
// У глагола заполнены только те времена, в которых он встречается в заготовках.
// Остальные — null. Это не задел «на потом», а защита: выдуманная форма
// невидима, пока ею не воспользуются, а null молча отсекает вариант (см.
// expandUnits в generate.ts). Тест требует, чтобы для времени своей заготовки
// форма БЫЛА.
//
// Вид глагола выбран так, чтобы фраза звучала естественно, а не по таблице:
// настоящее «звоню», прошедшее «звонил», будущее «позвоню». Present Perfect
// переводится прошедшим, кроме случаев с since и for, — там русский требует
// настоящего («Мы живём здесь с 2015 года»), и заготовка помечена ruTense.
// ─────────────────────────────────────────────────────────────────────────────

import type { Person } from "./sentenceUnits";

/** Какое РУССКОЕ время нужно переводу. К английскому привязано, но не равно ему. */
export type RuTense = "present" | "past" | "future";

/** я | ты | он, она, оно | мы | они */
export type RuPersonRow = readonly [string, string, string, string, string];

/** он | она | оно | они */
export type RuPastRow = readonly [string, string, string, string];

export type RuVerbForms = {
  present?: RuPersonRow;
  past?: RuPastRow;
  future?: RuPersonRow;
};

