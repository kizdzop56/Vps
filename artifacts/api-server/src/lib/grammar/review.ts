// ─────────────────────────────────────────────────────────────────────────────
// Повторение ошибок раздела «Учёба».
//
// ── Зачем ───────────────────────────────────────────────────────────────────
// Претензия была такая: формы, времена и сборку предложений ученик проходит за
// день, и дальше приложение для него мёртвое. Причин две, и объём банка — только
// вторая.
//
// Первая в том, что у грамматики НЕТ ПАМЯТИ. В словах есть интервальное
// повторение: ошибся — слово вернётся через десять минут, потом через день,
// потом через неделю. В грамматике ученик ошибался на «did you went», получал
// разбор и больше это задание не видел никогда. Отсюда и ощущение конечности:
// раздел не возвращает ничего, а значит его действительно можно «пройти».
//
// Здесь появляется то же, что в словах: ошибка возвращается по расписанию, пока
// не будет отработана. Это не увеличивает банк, но убирает саму возможность
// «пройти всё»: пока есть промахи, каждый день есть что повторять.
//
// ── Ничего не хранится ──────────────────────────────────────────────────────
// Состояние повторений ВЫВОДИТСЯ из grammar_log, а не пишется в отдельную
// таблицу. Причина та же, по которой так сделаны медали рейда: в журнале уже
// лежит всё нужное (номер задания, верно или нет, когда), и вторая копия правды
// обязательно разъедется с первой. Плюс приземлённое соображение: Render
// деплоится обычным пушем, миграции не гоняются, а новая таблица потребовала бы
// правки ensureSchema и разъехалась бы на любой базе, куда она не доехала.
//
// Следствия, которые стоит знать:
//   • расписание пересчитывается на каждый запрос — это дешёвая арифметика по
//     нескольким сотням строк, но не по всей истории (см. выборку в маршруте);
//   • изменение лестницы интервалов задним числом меняет расписание всем сразу.
//     Для повторений это нормально: срок — не награда, его нельзя «потерять».
//
// ── Кто попадает в повторения ───────────────────────────────────────────────
// ТОЛЬКО задания, на которых ученик ошибся. Задание, решённое с первого раза,
// в повторения не идёт: оно и так вернётся само, когда ротация дойдёт до своей
// порции банка (см. шапку engine.ts). Тащить в повторения всё подряд значило бы
// сделать вторую ротацию поверх первой.
//
// ── Лестница интервалов ─────────────────────────────────────────────────────
// Своя, не как у слов. Слово — это узнавание, ему нужны минуты на первых
// уровнях. Грамматическая ошибка — это неверное ПРАВИЛО, и возвращать его через
// минуту бессмысленно: ученик просто повторит только что прочитанный разбор по
// памяти, не вспоминая правило.
//
//   уровень 0 → 10 минут   (в тот же вечер, но не в том же заходе)
//   уровень 1 → 1 день
//   уровень 2 → 3 дня
//   уровень 3 → неделя
//   уровень 4 → три недели
//   уровень 5 → ошибка отработана, из повторений уходит
//
// Пять верных ответов, растянутых почти на месяц. Меньше — и «отработано»
// означало бы «повезло дважды подряд».
//
// ── Опечатка уровень не поднимает ───────────────────────────────────────────
// В грамматике опечатка прощается только в длинных словах и только когда ответ
// не совпал с другой формой глагола (см. шапку engine.ts). То есть принятая
// опечатка — это «правило знает, написал криво». Ответ засчитан, но следующий
// срок считается от того же уровня: ровно роль оценки hard в словах.
//
// ── Побочный эффект, о котором лучше знать заранее ──────────────────────────
// Ответы из повторения пишутся в журнал со своим настоящим режимом (его даёт
// сам номер задания, см. topicOf в routes/grammar.ts). Это правильно для
// статистики и медалей, но заодно двигает курсор ротации того режима: двенадцать
// повторений сдвинут обычную подборку на одну порцию вперёд. Задания при этом не
// теряются — на следующем круге порядок тасуется заново, — а различать ответы по
// происхождению было бы можно только новой колонкой в БД, то есть ценой
// миграции. Не стоит того.
// ─────────────────────────────────────────────────────────────────────────────

/** Строка журнала в том виде, в котором она нужна расписанию. */
export type GrammarAnswerLike = {
  taskId: string;
  correct: boolean;
  /** Ответ принят с опечаткой: уровень такой ответ не поднимает. */
  typo: boolean;
  answeredAt: Date;
};

/** Через сколько минут ошибка вернётся, по уровню отработки. */
export const GRAMMAR_REVIEW_INTERVAL_MIN: Record<number, number> = {
  0: 10,      // 10 минут
  1: 1440,    // сутки
  2: 4320,    // 3 дня
  3: 10080,   // неделя
  4: 30240,   // 3 недели
};

/** С этого уровня ошибка считается отработанной и в повторения не идёт. */
export const GRAMMAR_REVIEW_FIXED_LEVEL = 5;

export type GrammarReviewState = {
  taskId: string;
  /** 0…4 — сколько верных ответов подряд уже набрано после последней ошибки. */
  level: number;
  /** Сколько раз ученик ошибался на этом задании за всю историю. */
  wrongs: number;
  /** Когда отвечали в последний раз. */
  lastAt: Date;
  /** Когда задание нужно показать снова. */
  dueAt: Date;
};

function intervalMinutes(level: number): number {
  return GRAMMAR_REVIEW_INTERVAL_MIN[level] ?? GRAMMAR_REVIEW_INTERVAL_MIN[0]!;
}

/** Срок следующего показа от момента ответа. */
function dueFrom(at: Date, level: number): Date {
  return new Date(at.getTime() + intervalMinutes(level) * 60_000);
}

/**
 * Расписание повторений по журналу ответов.
 *
 * Журнал обходится в хронологическом порядке — иначе последний ответ не
 * определял бы состояние. Порядок наводится здесь же: маршрут читает строки
 * так, как удобнее базе, а не так, как удобно этой функции.
 *
 * Отработанные задания в результат не попадают: расписание отвечает на вопрос
 * «что ещё нужно повторять», а не «на чём ученик когда-либо спотыкался».
 */
export function reviewStates(answers: GrammarAnswerLike[]): Map<string, GrammarReviewState> {
  const sorted = [...answers].sort((a, b) => a.answeredAt.getTime() - b.answeredAt.getTime());
  const states = new Map<string, GrammarReviewState>();

  for (const answer of sorted) {
    const state = states.get(answer.taskId);

    // Первое появление задания в журнале. В повторения оно попадает только с
    // ОШИБКИ: решённое с первого раза вернётся обычной ротацией банка.
    if (!state) {
      if (answer.correct) continue;
      states.set(answer.taskId, {
        taskId: answer.taskId,
        level: 0,
        wrongs: 1,
        lastAt: answer.answeredAt,
        dueAt: dueFrom(answer.answeredAt, 0),
      });
      continue;
    }

    if (!answer.correct) {
      // Снова мимо: начинаем отработку заново. Отработанное задание таким
      // ответом возвращается в повторения — за этим и нужен полный обход.
      state.level = 0;
      state.wrongs += 1;
    } else if (!answer.typo) {
      state.level = Math.min(GRAMMAR_REVIEW_FIXED_LEVEL, state.level + 1);
    }

    state.lastAt = answer.answeredAt;
    state.dueAt = dueFrom(answer.answeredAt, state.level);
  }

  for (const [id, state] of states) {
    if (state.level >= GRAMMAR_REVIEW_FIXED_LEVEL) states.delete(id);
  }

  return states;
}

/**
 * Что показать прямо сейчас: созревшие ошибки, самые давние впереди.
 *
 * Порядок по сроку, а не по числу промахов. Задание, ждавшее неделю, ученик
 * успел забыть целиком, а свежая ошибка ещё держится в голове — и повторять её
 * первой значит потратить заход на то, что и так помнится.
 */
export function dueReviews(
  states: Map<string, GrammarReviewState> | GrammarReviewState[],
  now: Date = new Date(),
  limit = 12,
): GrammarReviewState[] {
  const list = Array.isArray(states) ? states : [...states.values()];
  return list
    .filter((s) => s.dueAt.getTime() <= now.getTime())
    .sort((a, b) => a.dueAt.getTime() - b.dueAt.getTime())
    .slice(0, Math.max(0, limit));
}

export type GrammarReviewSummary = {
  /** Сколько ошибок ждут повторения прямо сейчас. */
  due: number;
  /** Сколько ошибок вообще в работе: и созревшие, и те, что ждут срока. */
  pool: number;
  /** Когда придёт ближайшая, если сейчас пусто. null — ждать нечего. */
  nextDueAt: Date | null;
};

/**
 * Сводка для оглавления раздела.
 *
 * nextDueAt нужен ради честного пустого экрана: «ошибок к повторению нет» без
 * продолжения читается как «раздел кончился», а «следующее повторение завтра» —
 * как расписание.
 */
export function reviewSummary(
  states: Map<string, GrammarReviewState> | GrammarReviewState[],
  now: Date = new Date(),
): GrammarReviewSummary {
  const list = Array.isArray(states) ? states : [...states.values()];
  const nowMs = now.getTime();

  let due = 0;
  let next: Date | null = null;
  for (const state of list) {
    if (state.dueAt.getTime() <= nowMs) {
      due += 1;
      continue;
    }
    if (!next || state.dueAt.getTime() < next.getTime()) next = state.dueAt;
  }

  return { due, pool: list.length, nextDueAt: next };
}
