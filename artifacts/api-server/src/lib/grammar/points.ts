// ─────────────────────────────────────────────────────────────────────────────
// Очки за грамматику и разбор слабых мест.
//
// ── Зачем очки ──────────────────────────────────────────────────────────────
// За слова очки шли, за времена и глаголы — ноль. Ребёнок замечает это сразу и
// начинает выбирать то, что «считается», даже когда нужнее ему обратное. Раздел
// без очков выглядит необязательным, сколько бы полезным он ни был.
//
// ── Ставка зависит от способа ответа, а не от режима ────────────────────────
// Письмо дороже выбора: ответ надо достать из головы, а не опознать среди
// четырёх. Сборка предложения — тоже воспроизведение, но слова даны, поэтому
// она посередине. Делить ставку по режимам («времена дороже глаголов») было бы
// произволом: трудность задаёт форма ответа, а не название раздела.
//
// ── Потолок отдельный и ниже словарного ─────────────────────────────────────
// В словах потолок 60 очков, здесь 30. Не потому, что грамматика менее ценна:
// один заход письмом даёт около 24 очков, и 60 хватило бы на три захода подряд.
// Три захода по одной теме — уже не занятие, а зубрёжка ради очков.
//
// Потолки НЕ общие: иначе утренние слова съедали бы весь дневной запас, и
// грамматика вечером не приносила бы ничего — то есть ровно та проблема, из-за
// которой очки здесь и появились.
//
// Модуль чистый (без БД и express) — тесты в points.test.ts.
// ─────────────────────────────────────────────────────────────────────────────

/** Как ученик отвечал. Совпадает с полем input у карточки задания. */
export type GrammarInput = "type" | "choice" | "assemble";

/**
 * Очки за верный ответ по способу ответа.
 *
 * Выбор из четырёх — узнавание, самое лёгкое. Сборка — воспроизведение, но слова
 * даны. Письмо — воспроизведение с нуля, самое дорогое.
 */
export const POINTS_BY_INPUT: Record<GrammarInput, number> = {
  choice: 1,
  assemble: 2,
  type: 2,
};

/** Дневной потолок очков за грамматику. Про 30 — см. шапку файла. */
export const DAILY_GRAMMAR_POINTS_CAP = 30;

/**
 * Очки за один ответ, без учёта потолка.
 *
 * Ответ с опечаткой стоит как верный. Наказывать за промах пальца после того,
 * как то же самое прощается в словах, было бы непоследовательно — и ребёнок это
 * заметит быстрее, чем мы.
 */
export function pointsForAnswer(input: GrammarInput, correct: boolean): number {
  if (!correct) return 0;
  return POINTS_BY_INPUT[input] ?? 0;
}

/** Сколько из заработанного реально начислить с учётом дневного потолка. */
export function awardableGrammarPoints(points: number, earnedToday: number): number {
  const left = DAILY_GRAMMAR_POINTS_CAP - Math.max(0, earnedToday);
  if (left <= 0) return 0;
  return Math.max(0, Math.min(points, left));
}

// ── Слабые места ────────────────────────────────────────────────────────────
//
// «Что даётся хуже всего» — единственная статистика, ради которой стоит вести
// журнал. «Сколько заходов сделано» не нужно никому.
//
// Считаем по ПОСЛЕДНИМ ответам, а не за всю историю. Ровно та же причина, по
// которой это было исправлено в марафоне слов: ранние ошибки иначе висят вечно,
// и тема остаётся «проблемной» уже после того, как ученик её освоил.

/** По скольким последним ответам судим о теме. */
export const RECENT_WINDOW = 60;

/** Меньше этого числа ответов — судить не по чему. */
export const MIN_ANSWERS_FOR_VERDICT = 4;

/** Точность ниже этой (в процентах) делает тему слабым местом. */
export const WEAK_ACCURACY = 70;

export type LogLike = {
  /** Время или глагол. Пусто — тема неизвестна, в статистику не идёт. */
  topic: string | null;
  mode: string;
  correct: boolean;
  answeredAt: Date;
};

export type TopicStat = {
  topic: string;
  mode: string;
  answers: number;
  correct: number;
  accuracy: number;
  /** Тема в работе: ответов достаточно, а точность ниже порога. */
  weak: boolean;
};

/**
 * Точность по темам за последние RECENT_WINDOW ответов каждой темы.
 *
 * Окно считается ПО ТЕМЕ, а не по всему журналу: иначе тема, которую не трогали
 * месяц, вылетала бы из статистики просто потому, что рядом много свежих
 * ответов по другой теме.
 *
 * Порядок результата: сначала самое слабое. Список нужен, чтобы решить, чем
 * заняться, поэтому сверху то, что требует внимания.
 */
export function topicStats(logs: LogLike[], window: number = RECENT_WINDOW): TopicStat[] {
  const byTopic = new Map<string, LogLike[]>();
  for (const log of logs) {
    const topic = (log.topic ?? "").trim();
    if (!topic) continue;
    const key = `${log.mode}:${topic}`;
    const list = byTopic.get(key) ?? [];
    list.push(log);
    byTopic.set(key, list);
  }

  const out: TopicStat[] = [];
  for (const [key, list] of byTopic) {
    const [mode = "", ...rest] = key.split(":");
    const topic = rest.join(":");
    // Свежие сверху, лишнее отбрасываем.
    const recent = [...list]
      .sort((a, b) => b.answeredAt.getTime() - a.answeredAt.getTime())
      .slice(0, Math.max(1, window));
    const correct = recent.filter((l) => l.correct).length;
    const accuracy = Math.round((correct / recent.length) * 100);
    out.push({
      topic,
      mode,
      answers: recent.length,
      correct,
      accuracy,
      weak: recent.length >= MIN_ANSWERS_FOR_VERDICT && accuracy < WEAK_ACCURACY,
    });
  }

  // Слабое вперёд, дальше по точности, дальше по алфавиту — чтобы порядок не
  // прыгал при равных числах.
  return out.sort((a, b) =>
    Number(b.weak) - Number(a.weak) ||
    a.accuracy - b.accuracy ||
    a.topic.localeCompare(b.topic),
  );
}
